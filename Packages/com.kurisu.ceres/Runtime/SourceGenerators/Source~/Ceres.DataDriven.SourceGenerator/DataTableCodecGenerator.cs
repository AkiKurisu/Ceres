using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Ceres.DataDriven.SourceGenerator;

[Generator]
public sealed class DataTableCodecGenerator : ISourceGenerator
{
    private const string Category = "Ceres.DataDriven";

    private const string Api = "global::Ceres.DataDriven.";

    private static readonly DiagnosticDescriptor UnsupportedType = new(
        "CERESDT001", "Unsupported DataTable type", "'{0}' cannot be encoded in a DataTable: {1}",
        Category, DiagnosticSeverity.Error, true);

    private static readonly DiagnosticDescriptor PartialRequired = new(
        "CERESDT002", "DataTable type must be partial", "'{0}' must be partial so the generated DataTable codec can reach non-public member '{1}'",
        Category, DiagnosticSeverity.Error, true);

    private static readonly DiagnosticDescriptor UnreachableMember = new(
        "CERESDT003", "Unreachable DataTable member", "Member '{1}' of '{0}' is not accessible to the generated DataTable codec: {2}",
        Category, DiagnosticSeverity.Error, true);

    private static readonly DiagnosticDescriptor ObjectReference = new(
        "CERESDT004", "DataTable rows cannot hold UnityEngine.Object", "Member '{1}' of '{0}' references a UnityEngine.Object; use SoftAssetReference instead",
        Category, DiagnosticSeverity.Error, true);

    private static readonly HashSet<string> UnityValueTypes = new()
    {
        "Vector2", "Vector3", "Vector4", "Quaternion", "Color", "Rect", "Bounds", "Color32", "Vector2Int", "Vector3Int"
    };

    public void Initialize(GeneratorInitializationContext context) => context.RegisterForSyntaxNotifications(() => new Receiver());

    public void Execute(GeneratorExecutionContext context)
    {
        if (context.SyntaxReceiver is not Receiver receiver || receiver.Candidates.Count == 0) return;
        var compilation = context.Compilation;
        var symbols = Symbols.Create(compilation);
        if (symbols == null) return;

        var roots = new List<INamedTypeSymbol>();
        var seen = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
        foreach (var declaration in receiver.Candidates)
        {
            var model = compilation.GetSemanticModel(declaration.SyntaxTree);
            if (model.GetDeclaredSymbol(declaration) is not INamedTypeSymbol type || !seen.Add(type)) continue;
            if (type.IsAbstract || type.TypeKind != TypeKind.Class || type.IsGenericType || type.ContainingType is { IsGenericType: true }) continue;
            if (type.AllInterfaces.Any(i => SymbolEqualityComparer.Default.Equals(i, symbols.Row))) roots.Add(type);
        }
        if (roots.Count == 0) return;

        var builder = new Builder(context, symbols);
        foreach (var root in roots) builder.Require(root, null);
        builder.Process();

        var registrations = new StringBuilder("// <auto-generated />\n");
        foreach (var codec in builder.Codecs)
        {
            if (codec.Failed) continue;
            context.AddSource(codec.HintName + ".DataTableCodec.g.cs", SourceText.From(Emit(codec), Encoding.UTF8));
            registrations.Append("[assembly: ").Append(Api).Append("DataTableCodec(typeof(").Append(codec.TypeName)
                .Append("), typeof(").Append(codec.CodecName).Append("))]\n");
        }
        context.AddSource("DataTableCodecRegistrations.g.cs", SourceText.From(registrations.ToString(), Encoding.UTF8));
    }

    private static string Emit(Codec codec)
    {
        var s = new StringBuilder("// <auto-generated />\n#pragma warning disable\n");
        string indent;
        string closing;
        if (codec.Nested)
        {
            var type = codec.Type;
            var containers = new Stack<INamedTypeSymbol>();
            for (var t = type; t != null; t = t.ContainingType) containers.Push(t);
            var ns = type.ContainingNamespace.IsGlobalNamespace ? null : type.ContainingNamespace.ToDisplayString();
            var close = new StringBuilder();
            if (ns != null)
            {
                s.Append("namespace ").Append(ns).Append("\n{\n");
                close.Insert(0, "}\n");
            }
            int depth = ns != null ? 1 : 0;
            foreach (var t in containers)
            {
                var pad = new string(' ', depth * 4);
                s.Append(pad).Append("partial ").Append(Keyword(t)).Append(' ').Append(t.Name).Append('\n').Append(pad).Append("{\n");
                close.Insert(0, pad + "}\n");
                depth++;
            }
            indent = new string(' ', depth * 4);
            closing = close.ToString();
            s.Append(indent).Append("[global::UnityEngine.Scripting.Preserve]\n")
                .Append(indent).Append("internal sealed class __CeresDataTableCodec : ");
        }
        else
        {
            s.Append("namespace Ceres.Generated.DataTables\n{\n");
            indent = "    ";
            closing = "}\n";
            s.Append(indent).Append("[global::UnityEngine.Scripting.Preserve]\n")
                .Append(indent).Append("internal sealed class ").Append(codec.HintName).Append("_DataTableCodec : ");
        }
        var t2 = codec.TypeName;
        var i2 = indent + "    ";
        var i3 = i2 + "    ";
        s.Append(Api).Append("DataTableObjectCodec<").Append(t2).Append(">\n").Append(indent).Append("{\n");

        for (int i = 0; i < codec.Members.Count; i++)
        {
            var member = codec.Members[i];
            if (member.Value.Inline != null) continue;
            s.Append(i2).Append("private ").Append(member.Value.CodecType).Append(" _c").Append(i).Append(";\n");
            s.Append(i2).Append("private ").Append(member.Value.CodecType).Append(" C").Append(i).Append(" => _c").Append(i)
                .Append(" ??= ").Append(member.Value.CodecExpression).Append(";\n");
        }

        s.Append(i2).Append("protected override int MemberCount => ").Append(codec.Members.Count).Append(";\n");

        s.Append(i2).Append("protected override ").Append(Api).Append("DataTableMember[] CreateMembers() => new ").Append(Api).Append("DataTableMember[]\n")
            .Append(i2).Append("{\n");
        for (int i = 0; i < codec.Members.Count; i++)
        {
            var member = codec.Members[i];
            s.Append(i3).Append("new ").Append(Api).Append("DataTableMember(\"").Append(member.Name).Append("\", ")
                .Append(member.Value.Inline != null ? member.Value.CodecExpression : "C" + i).Append("),\n");
        }
        s.Append(i2).Append("};\n");

        s.Append(i2).Append("protected override ").Append(t2).Append(" Create() => new ").Append(t2).Append("();\n");

        s.Append(i2).Append("protected override void ReadMembers(ref global::Ceres.DataDriven.DataTableReader reader, ref ").Append(t2).Append(" value)\n")
            .Append(i2).Append("{\n");
        for (int i = 0; i < codec.Members.Count; i++)
        {
            var member = codec.Members[i];
            s.Append(i3).Append("value.").Append(member.Access).Append(" = ")
                .Append(member.Value.Inline != null ? member.Value.Inline.Read : "C" + i + ".Read(ref reader)").Append(";\n");
        }
        s.Append(i2).Append("}\n");

        s.Append(i2).Append("protected override void WriteMembers(global::Ceres.DataDriven.DataTableWriter writer, ").Append(t2).Append(" value)\n")
            .Append(i2).Append("{\n");
        for (int i = 0; i < codec.Members.Count; i++)
        {
            var member = codec.Members[i];
            var access = "value." + member.Access;
            s.Append(i3).Append(member.Value.Inline != null
                ? string.Format(member.Value.Inline.Write, access)
                : "C" + i + ".Write(writer, " + access + ")").Append(";\n");
        }
        s.Append(i2).Append("}\n");

        s.Append(indent).Append("}\n").Append(closing);
        return s.ToString();
    }

    private static string Keyword(INamedTypeSymbol type)
    {
        if (type.DeclaringSyntaxReferences.Any(reference => reference.GetSyntax() is RecordDeclarationSyntax)) return "record";
        return type.IsValueType ? "struct" : "class";
    }

    private sealed class Symbols
    {
        public INamedTypeSymbol Row;
        public INamedTypeSymbol EditorOnly;
        public INamedTypeSymbol NonSerialized;
        public INamedTypeSymbol SerializeField;
        public INamedTypeSymbol SerializeReference;
        public INamedTypeSymbol UnityObject;
        public INamedTypeSymbol List;
        public INamedTypeSymbol Optional;
        public INamedTypeSymbol SoftReference;
        public INamedTypeSymbol GenericSoftReference;

        public static Symbols Create(Compilation compilation)
        {
            var symbols = new Symbols
            {
                Row = compilation.GetTypeByMetadataName("Ceres.DataDriven.IDataTableRow"),
                EditorOnly = compilation.GetTypeByMetadataName("Ceres.DataDriven.EditorOnlyAttribute"),
                NonSerialized = compilation.GetTypeByMetadataName("System.NonSerializedAttribute"),
                SerializeField = compilation.GetTypeByMetadataName("UnityEngine.SerializeField"),
                SerializeReference = compilation.GetTypeByMetadataName("UnityEngine.SerializeReference"),
                UnityObject = compilation.GetTypeByMetadataName("UnityEngine.Object"),
                List = compilation.GetTypeByMetadataName("System.Collections.Generic.List`1"),
                Optional = compilation.GetTypeByMetadataName("Ceres.Optional`1"),
                SoftReference = compilation.GetTypeByMetadataName("Ceres.Resource.SoftAssetReference"),
                GenericSoftReference = compilation.GetTypeByMetadataName("Ceres.Resource.SoftAssetReference`1")
            };
            return symbols.Row == null || symbols.EditorOnly == null ? null : symbols;
        }
    }

    private sealed class Inline
    {
        public string Read;

        /// <summary>
        /// Format string taking the member access expression
        /// </summary>
        public string Write;
    }

    private sealed class Value
    {
        public string CodecType;

        public string CodecExpression;

        public Inline Inline;
    }

    private sealed class Member
    {
        public string Name;

        /// <summary>
        /// Member access expression in generated code
        /// </summary>
        public string Access;

        public Value Value;
    }

    private sealed class Codec
    {
        public INamedTypeSymbol Type;

        public string TypeName;

        public string HintName;

        public string CodecName;

        public bool Nested;

        public bool Failed;

        public readonly List<Member> Members = new();
    }

    private sealed class Builder
    {
        private readonly GeneratorExecutionContext _context;

        private readonly Symbols _symbols;

        private readonly Dictionary<INamedTypeSymbol, Codec> _codecs = new(SymbolEqualityComparer.Default);

        private readonly Queue<(INamedTypeSymbol Type, Location Location)> _pending = new();

        public Builder(GeneratorExecutionContext context, Symbols symbols)
        {
            _context = context;
            _symbols = symbols;
        }

        public IEnumerable<Codec> Codecs => _codecs.Values;

        public void Require(INamedTypeSymbol type, Location location)
        {
            if (_codecs.ContainsKey(type)) return;
            _codecs.Add(type, null);
            _pending.Enqueue((type, location));
        }

        public void Process()
        {
            while (_pending.Count > 0)
            {
                var (type, location) = _pending.Dequeue();
                _codecs[type] = Build(type, location ?? type.Locations.FirstOrDefault());
            }
        }

        private Codec Build(INamedTypeSymbol type, Location location)
        {
            var typeName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var hint = typeName.Replace("global::", string.Empty);
            hint = new string(hint.Select(c => char.IsLetterOrDigit(c) ? c : '_').ToArray());
            var codec = new Codec { Type = type, TypeName = typeName, HintName = hint };
            var own = SymbolEqualityComparer.Default.Equals(type.ContainingAssembly, _context.Compilation.Assembly);

            if (type.IsAbstract)
            {
                Fail(codec, UnsupportedType, location, type.ToDisplayString(), "abstract types are not supported");
                return codec;
            }
            if (type.IsGenericType)
            {
                Fail(codec, UnsupportedType, location, type.ToDisplayString(), "generic types are not supported");
                return codec;
            }
            if (type.TypeKind == TypeKind.Class && !type.InstanceConstructors.Any(c => c.Parameters.Length == 0 && Reachable(c, own)))
            {
                Fail(codec, UnsupportedType, location, type.ToDisplayString(), "it needs an accessible parameterless constructor");
                return codec;
            }
            if (!TypeReachable(type, own))
            {
                Fail(codec, UnsupportedType, location, type.ToDisplayString(), "the type is not accessible from generated code in this assembly");
                return codec;
            }

            var chain = new Stack<INamedTypeSymbol>();
            for (var t = type; t != null && t.SpecialType != SpecialType.System_Object && t.SpecialType != SpecialType.System_ValueType; t = t.BaseType)
            {
                chain.Push(t);
            }
            foreach (var declaring in chain)
            {
                foreach (var field in declaring.GetMembers().OfType<IFieldSymbol>())
                {
                    if (field.IsStatic || field.IsConst || field.IsReadOnly) continue;
                    if (Has(field, _symbols.NonSerialized)) continue;
                    bool serializeField = Has(field, _symbols.SerializeField);
                    var property = field.AssociatedSymbol as IPropertySymbol;
                    if (field.IsImplicitlyDeclared && (property == null || !serializeField)) continue;
                    if (field.DeclaredAccessibility != Accessibility.Public && !serializeField) continue;
                    if (Has(field, _symbols.EditorOnly)) continue;
                    var fieldLocation = field.Locations.FirstOrDefault() ?? location;
                    if (_symbols.SerializeReference != null && Has(field, _symbols.SerializeReference))
                    {
                        Fail(codec, UnsupportedType, fieldLocation, type.ToDisplayString() + "." + field.Name, "[SerializeReference] is not supported");
                        continue;
                    }
                    if (property?.SetMethod is { IsInitOnly: true })
                    {
                        Fail(codec, UnsupportedType, fieldLocation, type.ToDisplayString() + "." + property.Name, "init accessors are not supported");
                        continue;
                    }
                    var value = Classify(field.Type, codec, field, fieldLocation, false);
                    if (value == null) continue;
                    var accessors = property != null ? new ISymbol[] { property.GetMethod, property.SetMethod } : new ISymbol[] { field };
                    if (!accessors.All(accessor => Reachable(accessor, own)))
                    {
                        bool canNest = own && SymbolEqualityComparer.Default.Equals(declaring, type)
                                       && accessors.All(accessor => Reachable(accessor, own) || accessor.DeclaredAccessibility == Accessibility.Private);
                        if (!canNest)
                        {
                            Fail(codec, UnreachableMember, fieldLocation, type.ToDisplayString(), field.Name,
                                SymbolEqualityComparer.Default.Equals(declaring, type) ? "make it public or internal" : "it is declared non-public in a base type");
                            continue;
                        }
                        if (!IsPartial(type))
                        {
                            Fail(codec, PartialRequired, location, type.ToDisplayString(), field.Name);
                            continue;
                        }
                        codec.Nested = true;
                    }
                    codec.Members.Add(new Member { Name = field.Name, Access = "@" + (property?.Name ?? field.Name), Value = value });
                }
            }
            codec.CodecName = codec.Nested ? typeName + ".__CeresDataTableCodec" : "global::Ceres.Generated.DataTables." + hint + "_DataTableCodec";
            return codec;
        }

        private Value Classify(ITypeSymbol type, Codec owner, IFieldSymbol field, Location location, bool element)
        {
            var typeName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            switch (type.SpecialType)
            {
                case SpecialType.System_Boolean: return Primitive(typeName, "Boolean", "reader.ReadBoolean()");
                case SpecialType.System_SByte: return Primitive(typeName, "SByte", "reader.ReadSByte()");
                case SpecialType.System_Byte: return Primitive(typeName, "Byte", "reader.ReadByte()");
                case SpecialType.System_Int16: return Primitive(typeName, "Int16", "reader.ReadInt16()");
                case SpecialType.System_UInt16: return Primitive(typeName, "UInt16", "reader.ReadUInt16()");
                case SpecialType.System_Int32: return Primitive(typeName, "Int32", "reader.ReadInt32()");
                case SpecialType.System_UInt32: return Primitive(typeName, "UInt32", "reader.ReadUInt32()");
                case SpecialType.System_Int64: return Primitive(typeName, "Int64", "reader.ReadInt64()");
                case SpecialType.System_UInt64: return Primitive(typeName, "UInt64", "reader.ReadUInt64()");
                case SpecialType.System_Char: return Primitive(typeName, "Char", "reader.ReadChar()");
                case SpecialType.System_Single: return Primitive(typeName, "Single", "reader.ReadSingle()");
                case SpecialType.System_Double: return Primitive(typeName, "Double", "reader.ReadDouble()");
                case SpecialType.System_String: return Primitive(typeName, "String", "reader.ReadString() ?? string.Empty");
            }

            if (type.TypeKind == TypeKind.Enum && type is INamedTypeSymbol enumType)
            {
                var underlying = enumType.EnumUnderlyingType!;
                // Unity does not serialize 64-bit enumerations.
                if (underlying.SpecialType is SpecialType.System_Int64 or SpecialType.System_UInt64) return null;
                var underlyingName = underlying.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                var read = Classify(underlying, owner, field, location, element)!.Inline!.Read;
                return new Value
                {
                    CodecType = Api + "DataTableCodec<" + typeName + ">",
                    CodecExpression = "new " + Api + "DataTableEnumCodec<" + typeName + ">()",
                    Inline = new Inline { Read = "(" + typeName + ")" + read, Write = "writer.Write((" + underlyingName + "){0})" }
                };
            }

            if (type is IArrayTypeSymbol array)
            {
                if (array.Rank != 1 || element) return null;
                var item = Classify(array.ElementType, owner, field, location, true);
                if (item == null) return null;
                var itemName = array.ElementType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                return Wrapped(typeName, "new " + Api + "DataTableArrayCodec<" + itemName + ">(" + item.CodecExpression + ")");
            }

            if (type is not INamedTypeSymbol named) return null;

            if (named.IsGenericType)
            {
                var definition = named.OriginalDefinition;
                var argument = named.TypeArguments[0];
                var argumentName = argument.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                if (SymbolEqualityComparer.Default.Equals(definition, _symbols.List))
                {
                    if (element) return null;
                    var item = Classify(argument, owner, field, location, true);
                    return item == null ? null : Wrapped(typeName, "new " + Api + "DataTableListCodec<" + argumentName + ">(" + item.CodecExpression + ")");
                }
                if (SymbolEqualityComparer.Default.Equals(definition, _symbols.GenericSoftReference))
                {
                    return Wrapped(typeName, "new " + Api + "DataTableSoftAssetReferenceCodec<" + argumentName + ">()");
                }
                if (SymbolEqualityComparer.Default.Equals(definition, _symbols.Optional))
                {
                    var item = Classify(argument, owner, field, location, false);
                    return item == null ? null : Wrapped(typeName, "new " + Api + "DataTableOptionalCodec<" + argumentName + ">(" + item.CodecExpression + ")");
                }
            }

            if (SymbolEqualityComparer.Default.Equals(named, _symbols.SoftReference))
            {
                return Wrapped(typeName, Api + "DataTableCodecs.SoftAssetReference");
            }

            if (named.ContainingNamespace?.ToDisplayString() == "UnityEngine" && UnityValueTypes.Contains(named.Name))
            {
                return Wrapped(typeName, Api + "DataTableCodecs." + named.Name);
            }

            if (_symbols.UnityObject != null && Inherits(named, _symbols.UnityObject))
            {
                Fail(owner, ObjectReference, location, owner.Type.ToDisplayString(), field.Name);
                return null;
            }

            if ((named.TypeKind == TypeKind.Class || named.TypeKind == TypeKind.Struct) && named.IsSerializable)
            {
                if (named.IsGenericType)
                {
                    Fail(owner, UnsupportedType, location, named.ToDisplayString(), "generic types are not supported");
                    return null;
                }
                if (!RegisteredByDeclaringAssembly(named)) Require(named, location);
                return Wrapped(typeName, Api + "DataTableCodec<" + typeName + ">.Default");
            }

            // Unity does not serialize other types, so neither does the table.
            return null;
        }

        private static Value Primitive(string typeName, string codec, string read) => new()
        {
            CodecType = Api + "DataTableCodec<" + typeName + ">",
            CodecExpression = Api + "DataTableCodecs." + codec,
            Inline = new Inline { Read = read, Write = "writer.Write({0})" }
        };

        private static Value Wrapped(string typeName, string expression) => new()
        {
            CodecType = Api + "DataTableCodec<" + typeName + ">",
            CodecExpression = expression
        };

        private bool RegisteredByDeclaringAssembly(INamedTypeSymbol type)
        {
            if (SymbolEqualityComparer.Default.Equals(type.ContainingAssembly, _context.Compilation.Assembly)) return false;
            return type.ContainingAssembly.GetAttributes().Any(attribute =>
                attribute.AttributeClass?.ToDisplayString() == "Ceres.DataDriven.DataTableCodecAttribute"
                && attribute.ConstructorArguments.Length > 0
                && attribute.ConstructorArguments[0].Value is ITypeSymbol registered
                && SymbolEqualityComparer.Default.Equals(registered, type));
        }

        private void Fail(Codec codec, DiagnosticDescriptor descriptor, Location location, params object[] args)
        {
            codec.Failed = true;
            _context.ReportDiagnostic(Diagnostic.Create(descriptor, location, args));
        }

        private bool Reachable(ISymbol symbol, bool own)
        {
            return symbol.DeclaredAccessibility switch
            {
                Accessibility.Public => true,
                Accessibility.Internal or Accessibility.ProtectedOrInternal => own || symbol.ContainingAssembly.GivesAccessTo(_context.Compilation.Assembly),
                _ => false
            };
        }

        private bool TypeReachable(INamedTypeSymbol type, bool own)
        {
            for (var t = type; t != null; t = t.ContainingType)
            {
                if (!Reachable(t, own)) return false;
            }
            return true;
        }

        private static bool IsPartial(INamedTypeSymbol type)
        {
            for (var t = type; t != null; t = t.ContainingType)
            {
                foreach (var reference in t.DeclaringSyntaxReferences)
                {
                    if (reference.GetSyntax() is TypeDeclarationSyntax declaration && !declaration.Modifiers.Any(SyntaxKind.PartialKeyword)) return false;
                }
            }
            return true;
        }

        private static bool Has(ISymbol symbol, INamedTypeSymbol attribute)
        {
            return attribute != null && symbol.GetAttributes().Any(a => SymbolEqualityComparer.Default.Equals(a.AttributeClass, attribute));
        }

        private static bool Inherits(INamedTypeSymbol type, INamedTypeSymbol baseType)
        {
            for (var t = type; t != null; t = t.BaseType)
            {
                if (SymbolEqualityComparer.Default.Equals(t, baseType)) return true;
            }
            return false;
        }
    }

    private sealed class Receiver : ISyntaxReceiver
    {
        public readonly List<TypeDeclarationSyntax> Candidates = new();

        public void OnVisitSyntaxNode(SyntaxNode syntaxNode)
        {
            if (syntaxNode is TypeDeclarationSyntax { BaseList: not null } declaration and (ClassDeclarationSyntax or RecordDeclarationSyntax)) Candidates.Add(declaration);
        }
    }
}
